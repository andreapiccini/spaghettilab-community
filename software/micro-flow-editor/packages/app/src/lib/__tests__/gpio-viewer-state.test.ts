import { expect, it } from "vitest";
import type { ProjectV1 } from "@spaghettilab/domain";
import { compileConfig } from "@spaghettilab/config-compiler";
import { catalogGpioRelayDriver } from "../gpio-driver-presets.js";
import { planModuleImport, commitModuleImport } from "../module-import.js";
import { prepareDriverDeployment } from "../driver-deployment-plan.js";
import { oneShotDeploymentInput } from "../one-shot-deployment.js";
import { configHasContinuousSchedules } from "../stop-deployed-runtime.js";
import { DEFAULT_ENERGY, DISABLED_MQTT } from "../default-config-policy.js";
it("reads the actual relay GPIO for a viewer without executing relay commands", () => {
  const project = { coreBindings: [{ bindingId: "master", expectedDeviceId: "board", connectionProfileId: "usb" }], physicalGraphs: [], deviceGraphs: [], authoringMetadata: {} } as unknown as ProjectV1;
  const plan = planModuleImport(project, "master", "master:board", catalogGpioRelayDriver(), { name: "Function", variant: "v1", modes: [0,0,0,0], i2cSpeed: 0, local: true, backendPortId: 0 });
  const installed = commitModuleImport(project, plan, "relay", false, true);
  const graph = installed.deviceGraphs[0]!;
  const input = { physicalGraph: installed.physicalGraphs[0]!, processingGraph: { ...graph, nodes: [...graph.nodes, { layer: "device-processing" as const, id: "viewer", data: { kind: "block", blockTypeId: "ui.data_viewer", properties: {} } }], edges: [{ id: "state", source: graph.nodes[0]!.id, sourceHandle: "stato", target: "viewer", targetHandle: "value" }] }, mqtt: DISABLED_MQTT, connectivity: 0, energy: DEFAULT_ENERGY };
  input.processingGraph.nodes.push({ layer: "device-processing", id: "generator", data: { kind: "block", blockTypeId: "ab.square_wave", properties: { onDurationMs: 1000, offDurationMs: 2000, periodMs: 3000 } } });
  input.processingGraph.edges.push({ id: "drive", source: "generator", sourceHandle: "0", target: graph.nodes[0]!.id, targetHandle: "comando" });
  const deployment = prepareDriverDeployment(installed, "master", input);
  const observer = deployment.profiles.find(profile => profile.profileId.startsWith("flow.gpio-state."));
  expect(observer).toBeDefined();
  expect(deployment.signalObservations?.[0]?.key).toBe(deployment.observations?.[0]?.key);
  const withoutViewer = prepareDriverDeployment(installed, "master", { ...input, processingGraph: { ...input.processingGraph, nodes: input.processingGraph.nodes.filter(node => node.id !== "viewer"), edges: input.processingGraph.edges.filter(edge => edge.target !== "viewer") } });
  expect(withoutViewer.signalObservations).toHaveLength(1);
  expect(withoutViewer.profiles.some(profile => profile.profileId.startsWith("flow.gpio-state."))).toBe(true);
  expect(observer!.initOps).toEqual([]);
  expect(observer!.sampleOps.map(op => op.op)).toContain("GPIO_GET");
  expect(observer!.sampleOps.every(op => !["GPIO_SET", "GPIO_SET_VALUE", "GPIO_PULSE"].includes(op.op))).toBe(true);
  expect(deployment.observations?.[0]).toMatchObject({ valueKind: "boolean", label: "Stato", unit: "" });
  expect(deployment.observations?.[0]?.action).toBeUndefined();
  const compiled = compileConfig(oneShotDeploymentInput(deployment.input, [observer!.profileId]), deployment.options);
  if (!compiled.ok) throw new Error(JSON.stringify(compiled));
  expect(configHasContinuousSchedules(compiled.value)).toBe(false);
  expect(compiled.value.schedules.some(schedule => schedule.enabled)).toBe(true);
});
