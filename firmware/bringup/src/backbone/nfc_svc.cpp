bool nfc_reg_read(uint8_t address, uint8_t *value) {
    if (!nfc_ensure_rfal() || !value || address > 0x3F) return false;
    stop_wakeup();
    s_rf.rfalFieldOff();
    const ReturnCode rc = s_rf.st25r200ReadRegister(address, value);
    s_error = (uint8_t)rc;
    return rc == ERR_NONE;
}

bool nfc_reg_write(uint8_t address, uint8_t value) {
    if (!nfc_ensure_rfal() || address > 0x3F) return false;
    stop_wakeup();
    s_rf.rfalFieldOff();
    const ReturnCode rc = s_rf.st25r200WriteRegister(address, value);
    s_error = (uint8_t)rc;
    return rc == ERR_NONE;
}

bool nfc_scan(uint8_t antenna, uint8_t *found_antenna, uint8_t *tag_type,
              uint8_t *uid, uint8_t *uid_len) {
    s_scan_stage = 0;
    // Default and "scan both" (0) drive silkscreen ANT1 (RFO2). Dual-scan
    // used to report Antenna 2 as the last failure even when the tag sat on ANT1.
    if (antenna != 2) antenna = 1;
    s_scan_antenna = antenna;
    if (!nfc_ensure_rfal()) return false;
    stop_wakeup();
    const bool ok = scan_one(antenna, tag_type, uid, uid_len, false);
    if (ok && found_antenna) *found_antenna = antenna;
    if (!ok) {
        s_tag_present = false;
        if (found_antenna) *found_antenna = antenna;
        if (tag_type) *tag_type = 0;
        if (uid_len) *uid_len = 0;
    }
    const uint8_t scan_error = s_error;
    // Do not restart LPCD here: WakeUpModeStart blocked TWAI (status 255).
    s_rf.rfalFieldOff();
    s_error = scan_error;
    return ok;
}

bool nfc_tag_read(uint8_t antenna, uint8_t page, uint8_t data[4]) {
    if (!nfc_ensure_rfal()) return false;
    stop_wakeup();
    uint8_t type = 0;
    uint8_t uid[10], uid_len = 0;
    if (!data || !scan_one(antenna, &type, uid, &uid_len, true) || type != 1) {
        s_rf.rfalFieldOff();
        return false;
    }
    uint8_t rx[16] = {0};
    uint16_t rx_len = 0;
    const ReturnCode rc = s_nfc.rfalT2TPollerRead(page, rx, sizeof(rx), &rx_len);
    s_rf.rfalFieldOff();
    s_error = (uint8_t)rc;
    if (rc != ERR_NONE || rx_len < 4) return false;
    memcpy(data, rx, 4);
    return true;
}

bool nfc_tag_write(uint8_t antenna, uint8_t page, const uint8_t data[4]) {
    if (!nfc_ensure_rfal()) return false;
    stop_wakeup();
    uint8_t type = 0;
    uint8_t uid[10], uid_len = 0;
    if (!data || !scan_one(antenna, &type, uid, &uid_len, true) || type != 1) {
        s_rf.rfalFieldOff();
        return false;
    }
    const ReturnCode rc = s_nfc.rfalT2TPollerWrite(page, data);
    s_rf.rfalFieldOff();
    s_error = (uint8_t)rc;
    return rc == ERR_NONE;
}

void nfc_tick(uint32_t now_ms) {
    (void)now_ms;
    if (!s_ready) {
        nfc_ensure_rfal();
        return;
    }
    if (!s_wakeup_enabled || !s_irq_pending) return;
    s_irq_pending = false;
    s_rf.rfalWorker();

    rfalWakeUpInfo info = {};
    if (s_rf.rfalWakeUpModeGetInfo(false, &info) != ERR_NONE) return;
    const bool load_changed = info.indAmp.irqWu || info.cap.irqWu;
    if (!load_changed && !info.irqWut) return;

    const uint8_t monitored = s_wakeup_antenna;
    stop_wakeup();
    if (load_changed) {
        uint8_t type = 0, uid_len = 0, uid[10] = {0};
        bool found = false;
        uint8_t found_ant = 0;
        for (uint8_t ant = 1; ant <= 2; ++ant) {
            if (scan_one(ant, &type, uid, &uid_len, false)) {
                found = true;
                found_ant = ant;
                break;
            }
        }
        if (!found) {
            s_tag_present = false;
            s_antenna = 0;
            s_tag_type = 0;
            s_uid_len = 0;
            // Absence/removal is a normal detector result, not an RFAL fault.
            s_error = 0;
        }
        start_wakeup(found ? found_ant : (monitored == 1 ? 2 : 1));
        return;
    }

    // With no tag, the timeout IRQ rotates the single wake-up detector over
    // ANT1 and ANT2. While a tag is present, stay on its antenna so its
    // removal creates the next load-change IRQ.
    start_wakeup(s_tag_present ? monitored : (monitored == 1 ? 2 : 1));
}

uint8_t nfc_detected_antenna(uint32_t now_ms) {
    (void)now_ms;
    return s_tag_present ? s_antenna : 0;
}
uint8_t nfc_cached_tag_type() { return s_tag_type; }
uint8_t nfc_cached_uid(uint8_t *uid, uint8_t cap) {
    const uint8_t n = s_uid_len < cap ? s_uid_len : cap;
    if (uid && n) memcpy(uid, s_uid, n);
    return n;
}
